// Helper to find quiz by materiId
export function getQuizByMateriId(materiId) {
  if (!materiId) return quizList[0];
  const cleanId = String(materiId).toLowerCase().trim();
  const normalized = cleanId.startsWith('materi-') ? cleanId : `materi-${cleanId}`;
  
  const found = quizList.find((q) => q.materiId === normalized || q.materiId === cleanId);
  return found || quizList[0];
}

